def parse_vb_width(svg_tag: str) -> float:
    m = re.search(r'viewBox\s*=\s*["\']\s*[-\d.]+\s+[-\d.]+\s+([\d.]+)\s+([\d.]+)', svg_tag)
    return float(m.group(1)) if m else 480.0


def normalize_one(svg_text: str, title_text: str) -> str:
    # Skip if already generated by svg_gen or truth_specs with full theme + title
    if 'data-monday-theme="1"' in svg_text:
        return svg_text

    # 1. Clean <svg> opening tag: ensure viewBox, remove fixed width/height
    def clean_svg_open(m):
        tag = m.group(0)
        if "viewBox" not in tag:
            wm = re.search(r'\bwidth\s*=\s*["\']([\d.]+)', tag)
            hm = re.search(r'\bheight\s*=\s*["\']([\d.]+)', tag)
            w = wm.group(1) if wm else "480"
            h = hm.group(1) if hm else "320"
            tag = tag[:-1] + f' viewBox="0 0 {w} {h}">'
        tag = re.sub(r'\s+\bwidth\s*=\s*["\'][^"\']*["\']', "", tag)
        tag = re.sub(r'\s+\bheight\s*=\s*["\'][^"\']*["\']', "", tag)
        return tag

    svg_text = re.sub(r"<svg\b[^>]*>", clean_svg_open, svg_text, count=1, flags=re.I | re.S)
    m_open = re.search(r"<svg\b[^>]*>", svg_text, re.I | re.S)
    vb_w = parse_vb_width(m_open.group(0)) if m_open else 480.0

    # 2. Inject <title> and <desc> if missing
    safe_title = html.escape(title_text or "Математическая иллюстрация")
    inject_meta = ""
    if "<title" not in svg_text.lower():
        inject_meta += f"\n  <title>{safe_title}</title>"
    if "<desc" not in svg_text.lower():
        inject_meta += f"\n  <desc>{safe_title}</desc>"

    has_dark = ("prefers-color-scheme: dark" in svg_text) or ("data-theme=" in svg_text)
    if not has_dark:
        inject_meta += f"\n  {THEME_STYLE}"
        # Map legacy hex colors in attributes
        for old_hex, var_ref in COLOR_MAP.items():
            svg_text = re.sub(re.escape(old_hex) + r"\b", var_ref, svg_text, flags=re.I)

    if inject_meta and m_open:
        pos = m_open.end()
        svg_text = svg_text[:pos] + inject_meta + svg_text[pos:]

    # 3. Ensure font-size meets >= 12px at 320px viewport width
    min_fs = math.ceil(12.2 * vb_w / 320.0)
    def bump_fs(m):
        prefix, val = m.group(1), float(m.group(2))
        if val < min_fs:
            return f"{prefix}{min_fs}"
        return m.group(0)

    svg_text = re.sub(r'(font-size\s*=\s*["\'])(\d+(?:\.\d+)?)', bump_fs, svg_text)
    svg_text = re.sub(r'(font-size\s*:\s*)(\d+(?:\.\d+)?)px', lambda m: f"{m.group(1)}{max(float(m.group(2)), min_fs):g}px", svg_text)

    return svg_text


def run():
    rows = list(csv.DictReader(INVENTORY_CSV.open(encoding="utf-8")))
    changed = 0
    for r in rows:
        fp = ROOT / r["file"]
        if not fp.exists() or fp.suffix != ".svg":
            continue
        orig = fp.read_text(encoding="utf-8", errors="replace")
        # Extract first formula name for <title>/<desc>
        m_name = re.search(r"\(([^)]+)\)", r["formulas"])
        title = m_name.group(1) if m_name else r["image_id"]
        updated = normalize_one(orig, title)
        if updated != orig:
            fp.write_text(updated, encoding="utf-8")
            changed += 1
    print(f"Normalized {changed} SVGs")


if __name__ == "__main__":
    run()
